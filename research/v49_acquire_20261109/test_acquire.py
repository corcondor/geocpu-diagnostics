class Idempotent(Base):
    def test_second_run_downloads_nothing_and_rewrites_nothing(self):
        self.run_acquire()
        before = stat_snapshot(self.ext)
        self.hub.downloads.clear()
        res = self.run_acquire()
        self.assertEqual(self.hub.downloads, [])
        self.assertEqual(stat_snapshot(self.ext), before)                                           # not one file touched (mtime + size)
        self.assertTrue(all(f["status"] == "skipped_existing" for d in res["datasets"].values() for f in d["files"]))
        self.assertTrue(all(d["provenance"].startswith("kept") for d in res["datasets"].values()))
        self.assertEqual(res["downloaded_bytes"], 0)

    def test_resumes_after_a_failure_in_the_middle(self):
        self.hub.corrupt[("orgB/qa", "data/train/q1.json")] = b'{"data": [4, 5, 6, 8]}'              # same size, one byte different
        with self.assertRaises(A.VerificationError):
            self.run_acquire()
        self.assertTrue((self.ext / "orgA__coding/provenance.json").is_file())                      # dataset 1 finished
        self.assertFalse((self.ext / "orgB__qa/provenance.json").exists())                          # dataset 2 did not
        self.assertFalse((self.ext / "orgB__qa/data/train/q1.json").exists())
        del self.hub.corrupt[("orgB/qa", "data/train/q1.json")]
        self.hub.downloads.clear()
        res = self.run_acquire()
        st = {f["dest_rel"]: f["status"] for f in res["datasets"]["orgB/qa"]["files"]}
        self.assertEqual(st["orgB__qa/README.md"], "skipped_existing")
        self.assertEqual(st["orgB__qa/data/train/q1.json"], "downloaded")
        self.assertEqual(res["datasets"]["orgA/coding"]["provenance"], "kept")
        self.assertNotIn("orgA/coding", {d.repo_id for d in self.hub.downloads})                    # dataset 1 was not fetched again

    def test_a_complete_part_file_from_a_crashed_run_is_finished_not_rewritten(self):
        data = self.hub.content[("orgA/coding", "data/train-0.parquet")]
        final = self.ext / "orgA__coding/data/train-0.parquet"
        final.parent.mkdir(parents=True)
        Path(str(final) + ".part").write_bytes(data)
        self.run_acquire()
        self.assertEqual(final.read_bytes(), data)
        self.assertEqual([x for x in files_of(self.ext) if ".stale" in x or x.endswith(".part")], [])

    def test_a_wrong_part_file_is_moved_aside_never_overwritten(self):
        final = self.ext / "orgA__coding/data/train-0.parquet"
        final.parent.mkdir(parents=True)
        Path(str(final) + ".part").write_bytes(b"half-written junk")
        self.run_acquire()
        self.assertEqual(final.read_bytes(), self.hub.content[("orgA/coding", "data/train-0.parquet")])
        stale = Path(str(final) + ".part.stale-1")
        self.assertEqual(stale.read_bytes(), b"half-written junk")                                  # kept, not deleted, not overwritten


class Refusals(Base):
    def test_existing_file_with_other_content_is_refused_and_untouched(self):
        for new in (b"X" * len(self.hub.content[("orgA/coding", "data/train-0.parquet")]), b"short"):    # same size / different size
            with self.subTest(len=len(new)):
                final = self.ext / "orgA__coding/data/train-0.parquet"
                final.parent.mkdir(parents=True, exist_ok=True)
                final.write_bytes(new)
                self.hub.downloads.clear()
                with self.assertRaises(A.ExistingFileMismatch):
                    self.run_acquire()
                self.assertEqual(final.read_bytes(), new)                                           # not overwritten
                self.assertEqual(self.hub.data_downloads(), [])                                     # and no data file was fetched for it

    def test_existing_dev_file_with_other_content_is_refused_too(self):
        final = self.ext / "do_not_train_dev/orgB__qa/data/dev/q_dev.json"
        final.parent.mkdir(parents=True)
        final.write_bytes(b'{"data": ["DEV"]}')
        with self.assertRaises(A.ExistingFileMismatch):
            self.run_acquire()
        self.assertEqual(final.read_bytes(), b'{"data": ["DEV"]}')

    def test_download_with_wrong_size_raises_and_nothing_lands_on_drive(self):
        self.hub.corrupt[("orgA/coding", "data/train-0.parquet")] = self.hub.content[("orgA/coding", "data/train-0.parquet")][:-1]
        with self.assertRaises(A.VerificationError) as cm:
            self.run_acquire()
        self.assertIn("size", str(cm.exception))
        self.assertFalse((self.ext / "orgA__coding/data/train-0.parquet").exists())
        self.assertEqual([x for x in files_of(self.ext) if x.endswith(".part")], [])
        self.assertFalse((self.ext / "orgA__coding/provenance.json").exists())

    def test_download_with_same_size_but_wrong_sha256_raises(self):
        good = self.hub.content[("orgC/hot", "distractor/train-0.parquet")]
        self.hub.corrupt[("orgC/hot", "distractor/train-0.parquet")] = good[:-1] + bytes([good[-1] ^ 1])
        with self.assertRaises(A.VerificationError) as cm:
            self.run_acquire()
        self.assertIn("sha256", str(cm.exception))
        self.assertFalse((self.ext / "orgC__hot/distractor/train-0.parquet").exists())

    def test_non_lfs_file_with_wrong_git_blob_id_raises(self):
        good = self.hub.content[("orgB/qa", "data/train/q0.json")]
        self.hub.corrupt[("orgB/qa", "data/train/q0.json")] = good[:-1] + bytes([good[-1] ^ 1])
        with self.assertRaises(A.VerificationError) as cm:
            self.run_acquire()
        self.assertIn("git blob", str(cm.exception))
        self.assertFalse((self.ext / "orgB__qa/data/train/q0.json").exists())

    def test_live_hub_listing_that_differs_from_the_planning_snapshot_stops_before_any_data_download(self):
        for ov in ({"size": 999}, {"lfs_sha256": "0" * 64}):
            with self.subTest(ov=ov):
                self.hub.live_override = {("orgC/hot", "distractor/train-0.parquet"): ov}
                self.hub.downloads.clear()
                with self.assertRaises(A.UpstreamDrift):
                    self.run_acquire()
                self.assertEqual(self.hub.data_downloads(), [])

    def test_a_file_missing_upstream_stops_the_run(self):
        self.table[0]["files"].append(A.F("data/train-1.parquet", 10, "train", sha256="1" * 64))
        with self.assertRaises(A.UpstreamDrift):
            self.run_acquire()

    def test_wrong_licence_on_a_card_stops_everything_before_data(self):
        c = self.pairs[2][1]
        card = b"---\nlicense: mit\n---\n# changed\n"
        c["README.md"] = card
        self.table[2]["files"][0] = A.F("README.md", len(card), "card", blob=git_blob(card))
