def sha(b):
    return hashlib.sha256(b).hexdigest()


def git_blob(b):
    return hashlib.sha1(b"blob %d\0" % len(b) + b).hexdigest()


def make_ds(key, repo, files, lic="apache-2.0", share_alike=False, adoption=None, check_names=()):
    """files: [(path, bytes, role, lfs)] -> (table entry, {path: bytes}); a card README.md with a front-matter licence is added."""
    card = f"---\nlicense: {lic}\nlanguage:\n- en\n---\n# {repo}\nAuthors: Alice Example and Bob Sample.\n".encode()
    content = {"README.md": card}
    entries = [A.F("README.md", len(card), "card", blob=git_blob(card))]
    for path, data, role, lfs in files:
        content[path] = data
        if lfs:
            entries.append(A.F(path, len(data), role, sha256=sha(data), pointer_blob=git_blob(b"pointer:" + data)))
        else:
            entries.append(A.F(path, len(data), role, blob=git_blob(data)))
    url = "https://creativecommons.org/licenses/by-sa/4.0/" if share_alike else "https://www.apache.org/licenses/LICENSE-2.0"
    ds = dict(key=key, repo=repo, planning_sha=hashlib.sha1(repo.encode()).hexdigest(), licenses=(lic,),
              license_name="Test licence", license_url=url, share_alike=share_alike, row_license=lic.upper(),
              row_source=f"{repo} - {lic}", language="en", rows_card="n/a", generator_notes=["generated by a test model"],
              quality_notes=["tiny"], adoption=adoption or {"status": "pending_checks", "text": "adoption: decided after the checks"},
              attribution=dict(title=f"Title of {repo}", authors="Alice Example, Bob Sample", source_url=f"https://huggingface.co/datasets/{repo}", extra=[]),
              check_names=list(check_names), files=entries)
    return ds, content


class FakeHub:
    """Stands in for HfApi and hf_hub_download."""

    def __init__(self, pairs):
        self.by_repo = {ds["repo"]: ds for ds, _ in pairs}
        self.content = {(ds["repo"], p): b for ds, c in pairs for p, b in c.items()}
        self.shas = {ds["repo"]: ds["planning_sha"] for ds, _ in pairs}
        self.corrupt = {}
        self.live_override = {}
        self.downloads = []
        self.api_calls = []

    def HfApi(self):
        return SimpleNamespace(dataset_info=self._dataset_info)

    def _dataset_info(self, repo_id, *, files_metadata=False, token=None, revision=None, **kw):
        self.api_calls.append((repo_id, files_metadata, token))
        sibs = []
        for f in self.by_repo[repo_id]["files"]:
            if (repo_id, f["path"]) not in self.content:                                              # a table entry the "Hub" does not have
                continue
            data = self.content[(repo_id, f["path"])]
            if f["sha256"]:
                lfs, blob = {"sha256": f["sha256"], "size": len(data), "pointer_size": 134}, f["pointer_blob"]
            else:
                lfs, blob = None, f["blob"]
            d = dict(size=len(data), blob=blob, lfs=lfs)
            ov = self.live_override.get((repo_id, f["path"]), {})
            if "lfs_sha256" in ov:
                d["lfs"] = dict(d["lfs"] or {}, sha256=ov["lfs_sha256"])
            d.update({k: v for k, v in ov.items() if k in ("size", "blob")})
            sibs.append(SimpleNamespace(rfilename=f["path"], size=d["size"], blob_id=d["blob"], lfs=d["lfs"]))
        return SimpleNamespace(sha=self.shas[repo_id], siblings=sibs)

    def hf_hub_download(self, repo_id, filename, *, repo_type=None, revision=None, local_dir=None, token=None, **kw):
        self.downloads.append(SimpleNamespace(repo_id=repo_id, filename=filename, repo_type=repo_type, revision=revision, local_dir=local_dir, token=token))
        data = self.corrupt.get((repo_id, filename), self.content[(repo_id, filename)])
        p = Path(local_dir) / filename
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        return str(p)

    def data_downloads(self):
        return [d for d in self.downloads if d.filename != "README.md"]


def dest_to_content_keys(table):
    return [A.dest_rel(ds, f) for ds in table for f in ds["files"]]


def tree(p):
    return sorted(str(x.relative_to(p)).replace("\\", "/") for x in Path(p).rglob("*"))


def files_of(p):
    return sorted(x for x in tree(p) if (Path(p) / x).is_file())


def stat_snapshot(p):
    out = {}
    for rel in files_of(p):
        st = os.stat(Path(p) / rel)
        out[rel] = (st.st_mtime_ns, st.st_size)
    return out


class Base(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)
        self.root = self.tmp / "GeoCPU_root"
        self.root.mkdir()
        p = mock.patch("os.fsync")                    # fsync costs ~0.5 s per file on this PC; the call itself is asserted in one test
        self.fsync = p.start()
        self.addCleanup(p.stop)
        self.stage = self.tmp / "stage"
        self.ext = self.root / A.EXTERNAL_DIRNAME
        self.logs = []
        a = make_ds("coding", "orgA/coding", [("data/train-0.parquet", b"A-train-bytes-0123456789" * 3, "train", True)])
        b = make_ds("qa", "orgB/qa", [("data/train/q0.json", b'{"data": [1, 2, 3]}', "train", False),
                                      ("data/train/q1.json", b'{"data": [4, 5, 6, 7]}', "train", False),
                                      ("data/dev/q_dev.json", b'{"data": ["dev"]}', "dev", False)],
                    lic="cc-by-sa-3.0", share_alike=True, check_names=["Alice Example", "Zed Missing"])
        c = make_ds("hot", "orgC/hot", [("distractor/train-0.parquet", b"C-train" * 9, "train", True),
                                        ("distractor/validation-0.parquet", b"C-valid" * 5, "validation", True)],
                    lic="cc-by-sa-4.0", share_alike=True)
        self.pairs = [a, b, c]
        self.table = [ds for ds, _ in self.pairs]
        self.hub = FakeHub(self.pairs)

    def run_acquire(self, **kw):
        kw.setdefault("now_utc", NOW)
        kw.setdefault("stage_dir", self.stage)
        kw.setdefault("datasets", self.table)
        kw.setdefault("allow_local", True)
        kw.setdefault("log", self.logs.append)
        with mock.patch.object(A, "HfApi", self.hub.HfApi), mock.patch.object(A, "hf_hub_download", self.hub.hf_hub_download):
            return A.acquire(self.root, **kw)

    def prov(self, folder):
        return json.loads((self.ext / folder / "provenance.json").read_text(encoding="utf-8"))


class FirstRun(Base):
    def test_layout_verification_and_no_leftovers(self):
        res = self.run_acquire()
        self.assertEqual(sorted(os.listdir(self.root)), [A.EXTERNAL_DIRNAME])                       # only the NEW folder appears under root
        for rel in ["orgA__coding/README.md", "orgA__coding/data/train-0.parquet", "orgA__coding/provenance.json", "orgA__coding/PROVENANCE.md",
                    "orgB__qa/data/train/q0.json", "orgB__qa/data/train/q1.json",
                    "do_not_train_dev/orgB__qa/data/dev/q_dev.json", "do_not_train_dev/DO_NOT_TRAIN.txt",
                    "orgC__hot/distractor/train-0.parquet", "do_not_train_validation/orgC__hot/distractor/validation-0.parquet",
                    "do_not_train_validation/DO_NOT_TRAIN.txt"]:
            self.assertTrue((self.ext / rel).is_file(), rel)
        self.assertFalse((self.ext / "orgB__qa/data/dev").exists())                                # dev never inside the dataset folder
        self.assertFalse((self.ext / "orgC__hot/distractor/validation-0.parquet").exists())
        self.assertEqual([x for x in files_of(self.ext) if x.endswith(".part")], [])
        self.assertEqual(files_of(self.stage), [])                                                # staged copies are removed after the verified copy
        self.assertGreaterEqual(self.fsync.call_count, len(dest_to_content_keys(self.table)))     # every Drive copy is flushed before the rename
        dest_to_content = {A.dest_rel(ds, f): self.hub.content[(ds["repo"], f["path"])] for ds in self.table for f in ds["files"]}
        for repo, d in res["datasets"].items():
            for f in d["files"]:
                self.assertEqual(f["status"], "downloaded", (repo, f))
                self.assertEqual((self.ext / f["dest_rel"]).read_bytes(), dest_to_content[f["dest_rel"]])      # byte-identical
        self.assertEqual(res["downloaded_bytes"], res["total_bytes"])
        self.assertEqual(len(dest_to_content), sum(len(d["files"]) for d in res["datasets"].values()))

    def test_hub_calls_are_pinned_anonymous_and_outside_drive(self):
        self.run_acquire()
        self.assertTrue(self.hub.downloads)
        for d in self.hub.downloads:
            self.assertEqual(d.repo_type, "dataset")
            self.assertEqual(d.revision, self.hub.shas[d.repo_id])                                  # pinned to the commit sha the API reported
            self.assertIs(d.token, False)                                                           # never sends a token
            self.assertTrue(A._is_within(d.local_dir, self.stage))
            self.assertFalse(A._is_within(d.local_dir, self.root))
        self.assertTrue(all(c[1] is True and c[2] is False for c in self.hub.api_calls))            # files_metadata=True, token=False

    def test_licence_is_checked_for_all_datasets_before_any_data_download(self):
        order = []
        orig = self.hub.hf_hub_download

        def spy(repo_id, filename, **kw):
            order.append(filename)
            return orig(repo_id, filename, **kw)
        self.hub.hf_hub_download = spy
        self.run_acquire()
        first_data = next(i for i, f in enumerate(order) if f != "README.md")
        self.assertEqual(order[:first_data].count("README.md"), 3)                                  # all three cards first


